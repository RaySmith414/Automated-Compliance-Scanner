"""Generate docs/CHECKS.md and docs/MAPPINGS.md from the YAML catalogs.

    python -m scanner.docs            write both files
    python -m scanner.docs --check    exit 1 if the files on disk are stale

The documents are generated so they cannot drift from what the scanner runs.
"""

import argparse
import sys
from pathlib import Path
from typing import Dict, List

from scanner.catalog import PLATFORMS, load_benchmark, load_checks, load_frameworks
from scanner.model import CATEGORIES, FRAMEWORK_KEYS

HEADER = "<!-- Generated by `python -m scanner.docs`. Edit scanner/data/*.yaml, not this file. -->\n\n"


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _cis_cell(check) -> str:
    if not check.is_cis:
        return "no"
    return f"yes ({check.cis_id})" if check.cis_id else "yes"


def checks_markdown() -> str:
    lines: List[str] = [HEADER + "# Check reference\n"]
    lines.append("Every check the scanner runs, grouped by platform and category. "
                 "\"Needs root\" means the check reports ERROR unless the scanner runs as root on Linux "
                 "or as an administrator on Windows.\n")
    for platform in PLATFORMS:
        checks = load_checks(platform)
        benchmark = load_benchmark(platform)
        lines.append(f"## {platform.capitalize()} ({len(checks)} checks)\n")
        lines.append(f"Benchmark family: {benchmark.get('family')}. "
                     f"Written against: {benchmark.get('written_against')}.\n")
        for category in CATEGORIES:
            rows = [c for c in checks if c.category == category]
            if not rows:
                continue
            lines.append(f"### {category.replace('_', ' ').capitalize()}\n")
            lines.append("| ID | Check | Severity | Needs root | CIS recommendation | Expected state | Remediation |")
            lines.append("| --- | --- | --- | --- | --- | --- | --- |")
            for check in rows:
                lines.append("| " + " | ".join([
                    check.id, _cell(check.title), check.severity, "yes" if check.requires_root else "no",
                    _cis_cell(check), _cell(check.expected), _cell(check.remediation),
                ]) + " |")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def mappings_markdown() -> str:
    frameworks = load_frameworks()
    lines: List[str] = [HEADER + "# Framework mappings\n"]
    lines.append("These mappings are an informative crosswalk prepared by the author for triage and reporting. "
                 "They are not an official mapping published by NIST, the AICPA, ISO or CIS. "
                 "Validate them against your own control set before you rely on them in an assessment.\n")
    for platform in PLATFORMS:
        lines.append(f"## {platform.capitalize()} checks\n")
        lines.append("| ID | Check | NIST SP 800-53 Rev. 5 | SOC 2 | ISO/IEC 27001:2022 |")
        lines.append("| --- | --- | --- | --- | --- |")
        for check in load_checks(platform):
            lines.append("| " + " | ".join([
                check.id, _cell(check.title), ", ".join(check.nist_800_53), ", ".join(check.soc2),
                ", ".join(check.iso_27001),
            ]) + " |")
        lines.append("")
    usage: Dict[str, Dict[str, List[str]]] = {key: {} for key in FRAMEWORK_KEYS}
    for platform in PLATFORMS:
        for check in load_checks(platform):
            for key in FRAMEWORK_KEYS:
                for control_id in getattr(check, key):
                    usage[key].setdefault(control_id, []).append(check.id)
    for key in FRAMEWORK_KEYS:
        section = frameworks[key]
        lines.append(f"## {section['label']}\n")
        if key == "nist_800_53":
            lines.append("| Control | Title | Baselines (SP 800-53B) | Checks |")
            lines.append("| --- | --- | --- | --- |")
        else:
            lines.append("| Control | Title | Checks |")
            lines.append("| --- | --- | --- |")
        for control_id, entry in section["controls"].items():
            cells = [control_id, _cell(entry["title"])]
            if key == "nist_800_53":
                cells.append(", ".join(entry["baselines"]))
            cells.append(", ".join(usage[key].get(control_id, [])))
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def documents() -> Dict[str, str]:
    return {"CHECKS.md": checks_markdown(), "MAPPINGS.md": mappings_markdown()}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Generate the check and mapping reference documents.")
    parser.add_argument("--out", default="docs", help="directory to write to (default: docs)")
    parser.add_argument("--check", action="store_true", help="only verify that the files on disk are current")
    args = parser.parse_args(argv)
    out = Path(args.out)
    stale = []
    for name, content in documents().items():
        target = out / name
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(str(target))
        else:
            out.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            print(f"wrote {target}")
    if stale:
        print("stale: " + ", ".join(stale) + ". Run `python -m scanner.docs`.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
